"""stack-composer: compose stack.yaml for one component: its entry file is the contract, the pin is an input, kustomize does the patching.

usage: stack_composer.py [--manifest <manifest.yaml> --cluster <name>] <values.yaml> <component> <entry file> <stack.yaml>

Input   <values.yaml>  the converged config (config-builder): the flag <component>_enabled, true when no config sets it
        <entry file>   the contract: the OCIRepository and the Kustomization of the component, with `tag: unpinned`. It is never written.
        <stack.yaml>   the stack of the cluster (sync/<name>/infra-stack.yaml) that Flux reads: it holds the pins
        --manifest     out/manifest.yaml: what `publish-artifact` recorded, components: <cluster>: <component>: {tag, digest}. Optional. No file, or no entry for the
                       component: no new pin. Ignored when the flag is false.
        --cluster      the name of the cluster in manifest.yaml: `sync:` in clusters/<cluster>/cluster.yaml. Needed with --manifest.

Model   The two kustomize folders are the strings of MODEL below. This code only writes them and the input files into a temporary folder:
        delete-patch  entry                              -> a delete patch
        stack         stack + add + patch + delete       -> the new stack
        Flag false:   delete the documents of the entry that are in the stack.
        Otherwise:    the documents that are in the stack patch it (fields are overridden, none is removed). The others are added.

Output  <stack.yaml>, written only after the new stack passes the checks: every dependsOn names a Kustomization of the stack.
        kustomize sorts the documents and the keys and drops the comments: the comments are in the entry files.

Words   document   one object of a YAML file (the parts of a file that `---` separates). The entry file has two: the pair.
        pair       the OCIRepository and the Kustomization of a component. Flux needs both.
        patch      a partial document. kustomize merges it into the document of the same kind, name and namespace.
"""

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

# The kustomize folders of the model: the kustomization.yaml of each step. The input files of a step are written next to it.
MODEL = {
    # step "delete-patch": the entry becomes a delete patch: every document gets `$patch: delete`. Inputs: entry.yaml.
    "delete-patch": """\
resources:
  - entry.yaml
patches:
  - target:
      kind: ".*"
    patch: |-
      - op: add
        path: /$patch
        value: delete
""",
    # step "stack": the new stack. Inputs: stack.yaml, and three files that can be empty:
    #   add.yaml     the entry documents that are not in the stack yet: they are added
    #   patch.yaml   the entry documents that are in the stack: each overrides the fields of the document of the same kind, name and namespace
    #   delete.yaml  the documents to remove ($patch: delete)
    # A patch needs a document to patch, and it cannot create one. That is why add.yaml and patch.yaml are two files.
    "stack": """\
resources:
  - stack.yaml
  - add.yaml
patches:
  - path: patch.yaml
  - path: delete.yaml
""",
}
HEADER = """\
# GENERATED by stack-composer (tools/): do not edit by hand. `just <component>/compose-stack` composes it from the flags `<component>_enabled` (config/),
# the entry file of each component (<component>/flux/stack.yaml) and the pins. The comments are in the entry files.
"""
# A digest from the registry looks like this: sha256: and 64 hex digits.
DIGEST = re.compile(r"^sha256:[0-9a-f]{64}$")


def step(name, files):
    """Run one kustomize folder of the model on some input files, and return what `kustomize build` prints."""
    with tempfile.TemporaryDirectory() as tmp:
        # 1. Write the kustomization.yaml of the step (MODEL[name]) into a temporary folder.
        (Path(tmp) / "kustomization.yaml").write_text(MODEL[name])
        # 2. Put the input files next to it. The kustomization names them (entry.yaml, stack.yaml, ...).
        for file, text in files.items():
            (Path(tmp) / file).write_text(text)
        # 3. Let kustomize apply the patches and print the result.
        try:
            done = subprocess.run(["kustomize", "build", tmp], check=False, capture_output=True, text=True)
        except FileNotFoundError:
            sys.exit("kustomize is not installed")
    if done.returncode:
        sys.exit(f"kustomize ({name}): {done.stderr.strip()}")
    return done.stdout


def load(text):
    """Return the documents of a YAML text as a list. An empty document is left out."""
    return [d for d in yaml.safe_load_all(text) if d]


def ident(doc):
    """The identity of a document: its kind and its name. For example ("Kustomization", "istio")."""
    return doc["kind"], doc["metadata"]["name"]


def dependency_errors(docs):
    """Return a message for each Kustomization that waits for a Kustomization that is not in the stack.

    A Kustomization with `dependsOn: [{name: spire}]` never starts when spire is not there. So this stops a disable that would break it.
    docs are the documents of the new stack.
    """
    # The names of all the Kustomizations of the stacks.
    present = {d["metadata"]["name"] for d in docs if d["kind"] == "Kustomization"}
    # Every "A waits for B" pair of the stack, as (A, the dependsOn entry of B).
    waits = [
        (d["metadata"]["name"], dep) for d in docs if d["kind"] == "Kustomization" for dep in (d.get("spec") or {}).get("dependsOn") or []
    ]
    # The pairs where B is not in the stack.
    return [
        f"{name} waits for {dep.get('name')}, which is not in the stack: add {dep.get('name')} or remove {name} first"
        for name, dep in waits
        if dep.get("name") not in present
    ]


def main():
    parser = argparse.ArgumentParser(description="Compose the stack of one component.")
    parser.add_argument("values", help="values.yaml of config-builder")
    parser.add_argument("component")
    parser.add_argument("entry", help="the entry file of the component")
    parser.add_argument("stack", help="the stack of the component, which is rewritten")
    parser.add_argument("--manifest", help="out/manifest.yaml: the tag and digest of the last publish of each component")
    parser.add_argument("--cluster", help="the name of the cluster in manifest.yaml")
    args = parser.parse_args()
    values_file, component, entry_file, stack_file = args.values, args.component, args.entry, args.stack

    # --- 1. Read and check the inputs. Nothing is written yet. ---

    # The flag of the component, for example istio_ingress_enabled. None means that no config sets it, and that means enabled.
    flag = (yaml.safe_load(Path(values_file).read_text()) or {}).get(component.replace("-", "_") + "_enabled")
    if flag is not None and not isinstance(flag, bool):  # the string "false" would pass as true, so only a real boolean is allowed
        sys.exit(f"{component}: the flag is {flag!r}, it must be true or false (a YAML boolean)")

    # The entry file (the contract). It must hold the pair of this component. Other documents are allowed.
    entry_text = Path(entry_file).read_text()
    entry = load(entry_text)
    if {("OCIRepository", component), ("Kustomization", component)} - {ident(d) for d in entry}:
        sys.exit(f"{entry_file}: it needs the OCIRepository and the Kustomization of {component}")

    # The pin: the tag and the digest that the last publish of this component wrote into the manifest. It is optional.
    pin = None
    if args.manifest:
        if not args.cluster:
            sys.exit("--manifest needs --cluster")
        try:
            manifest = yaml.safe_load(Path(args.manifest).read_text()) or {}
        except FileNotFoundError:  # no publish on this machine yet
            manifest = {}
        except (OSError, yaml.YAMLError) as e:
            sys.exit(f"{args.manifest}: {e}")
        components = (manifest.get("components") or {}) if isinstance(manifest, dict) else {}
        pin = ((components.get(args.cluster) or {}) if isinstance(components, dict) else {}).get(component)
    if pin and not (isinstance(pin, dict) and isinstance(pin.get("tag"), str) and pin["tag"] and DIGEST.match(str(pin.get("digest")))):
        sys.exit(f"{args.manifest}: {args.cluster}/{component} needs a tag and a digest (sha256:<64 hex digits>), found {pin}")
    if pin:
        pin = {"tag": pin["tag"], "digest": pin["digest"]}

    # --- 2. Decide what kustomize must do, and give it the input files. ---

    stack_text = Path(stack_file).read_text()
    in_stack = {ident(d) for d in load(stack_text)}  # which documents the stack has now
    # The input files of the "stack" step (MODEL["stack"]). An empty file means: nothing to do for that part.
    #   add.yaml    documents to add to the stack
    #   patch.yaml  documents that override the fields of documents that are in the stack already
    #   delete.yaml documents to remove from the stack
    files = {"stack.yaml": stack_text, "add.yaml": "", "patch.yaml": "", "delete.yaml": ""}

    if flag is False:
        # Disabled: remove the documents of the entry that are in the stack. A document that is not there needs no removal.
        gone = [d for d in entry if ident(d) in in_stack]
        if gone:
            # The "delete-patch" step turns these documents into `$patch: delete` documents.
            files["delete.yaml"] = step("delete-patch", {"entry.yaml": yaml.safe_dump_all(gone)})
    else:
        # Enabled. With a new pin, first put the pin into the entry (in memory only: the entry file is never written).
        if pin:
            for d in entry:
                if ident(d) == ("OCIRepository", component):
                    d["spec"].setdefault("ref", {}).update(pin)  # the tag and the digest of the pin

        # A patch can only change a document that exists. So split the entry: what the stack has gets patched, the rest gets added.
        present = [d for d in entry if ident(d) in in_stack]
        for d in present:
            # No new pin: the entry says `tag: unpinned`. If it patched the stack, it would erase the pin that the stack has.
            # So take spec.ref out of the patch, and the pin of the stack stays.
            if d["kind"] == "OCIRepository" and not pin:
                d["spec"].pop("ref", None)
        files["patch.yaml"] = yaml.safe_dump_all(present)
        # A new document is added as it is. Without a pin it keeps `tag: unpinned`, and Flux waits until it is pinned.
        files["add.yaml"] = yaml.safe_dump_all([d for d in entry if ident(d) not in in_stack])

    # --- 3. Let kustomize build the new stack: stack.yaml + add.yaml, with patch.yaml and delete.yaml applied. ---
    new_text = step("stack", files)

    # --- 4. Check the new stack. Write it only if the check passes, so a refused run leaves stack.yaml as it was. ---
    problems = dependency_errors(load(new_text))
    if problems:
        sys.exit("\n".join(problems))
    # The header goes first, then `---` (the start of the first document).
    Path(stack_file).write_text(HEADER + "---\n" + new_text)


if __name__ == "__main__":
    main()
